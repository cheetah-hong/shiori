#!/usr/bin/env python3
"""Dump the reference parser's output for every fixture page as JSON (<data>/reference_output.json).

The Dart port is checked entry by entry against this file
(packages/core/test/capture/reference_parity_test.dart). Re-run after changing a fixture:
    python3 tools/reference/dump_reference.py --data packages/core/test/fixtures/synthetic
    python3 tools/reference/dump_reference.py      # the recorded textbook pages (local only, see parse_eval.py)
"""
import json
import sys

import parse_eval as ref


def main():
    if not (ref.DATA / "ground_truth.json").is_file():
        sys.exit(f"ground truth not found in {ref.DATA} (set SHIORI_PRIVATE_DIR or pass --data DIR)")
    with open(ref.DATA / "ground_truth.json", encoding="utf-8") as f:
        gt = json.load(f)
    pages = []
    for pg in gt["pages"]:
        ja, ko = ref.load(pg["fixture"])
        tpl = ref.detect(ja)
        entries = (ref.parse_list if tpl == "list" else ref.parse_entry)(ja, ko)
        day, title, page = ref.footer_meta(ko, ja)
        pages.append({"fixture": pg["fixture"], "template": tpl,
                      "meta": {"day": day, "title": title, "page": page}, "entries": entries})
    out = ref.DATA / "reference_output.json"
    out.write_text(json.dumps({"_note": "Generated by tools/reference/dump_reference.py. Do not edit.",
                               "pages": pages}, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"wrote {out} ({sum(len(p['entries']) for p in pages)} entries)")


if __name__ == "__main__":
    main()
