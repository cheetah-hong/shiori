#!/usr/bin/env python3
"""Build the data tables the word extractor compiles in (packages/core/lib/src/extract/data/).

  python3 tools/extract/build_extract_data.py [--unihan ZIP] [--check]

Writes two Dart files from third-party data kept unchanged in the repository or downloaded:

  deconjugation_rules.dart   packages/core/third_party/jl/deconjugation_rules.json as a raw string
                             (Apache-2.0, see packages/core/third_party/jl/README.md)
  hanja_readings.dart        Korean readings (Unihan kHangul) of the Joyo and Jinmeiyo kanji.
                             A kanji without kHangul (a Japanese simplified form such as 験 or 図)
                             takes the readings of its old or traditional form (kJapaneseOldVariant,
                             kTraditionalVariant, kSemanticVariant, kZVariant) or of its NFC form
                             (compatibility ideographs). Unicode License v3, see
                             packages/core/third_party/unihan/README.md.

Unihan: --unihan points at Unihan.zip; without it the zip is read from tools/extract/.cache/ or
downloaded from unicode.org (https) and checked against UNIHAN_SHA256.
--check: exit 1 when a generated file differs from what this script would write.
Only the Python 3 standard library is used.
"""
from __future__ import annotations

import argparse
import collections
import hashlib
import io
import json
import sys
import unicodedata
import urllib.request
import zipfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CORE = REPO / "packages" / "core"
OUT_DIR = CORE / "lib" / "src" / "extract" / "data"
RULES_SOURCE = CORE / "third_party" / "jl" / "deconjugation_rules.json"
CACHE = Path(__file__).resolve().parent / ".cache"

UNIHAN_URL = "https://www.unicode.org/Public/18.0.0/ucd/Unihan.zip"
UNIHAN_VERSION = "18.0.0"
UNIHAN_SHA256 = "4c93ea9c1f636451729a840978f1667a53886af37ba854fdcce109721c63d43e"

# Variant fields tried, in order, for a kanji Unihan gives no Korean reading.
VARIANT_FIELDS = ("kJapaneseOldVariant", "kTraditionalVariant", "kSemanticVariant", "kZVariant")
# Then the other form a kJoyoKanji / kJinmeiyoKanji value names (U+XXXX).
LOOKUP_FIELDS = (*VARIANT_FIELDS, "official")
ENTRIES_PER_LINE = 16


def rules_dart(rules_json: str) -> str:
    json.loads(rules_json)  # fail here, not in the app, when the file is not JSON
    if "'''" in rules_json:
        raise ValueError("rules file contains ''' and cannot be a raw Dart string")
    return (
        "// Generated by tools/extract/build_extract_data.py. Do not edit.\n"
        "// Source: packages/core/third_party/jl/deconjugation_rules.json (Apache-2.0).\n"
        "\n"
        "/// The deconjugation rules, unchanged from the source file.\n"
        f"const String deconjugationRulesJson = r'''{rules_json}''';\n"
    )


def read_unihan(zip_bytes: bytes) -> dict[str, list[str]]:
    """Field files of Unihan.zip by name, as lines."""
    with zipfile.ZipFile(io.BytesIO(zip_bytes)) as z:
        return {
            name: z.read(name).decode("utf-8").splitlines()
            for name in ("Unihan_Readings.txt", "Unihan_Variants.txt", "Unihan_OtherMappings.txt")
        }


def _fields(lines: list[str]):
    for line in lines:
        if line.startswith("U+"):
            cp, field, value = line.split("\t", 2)
            yield int(cp[2:], 16), field, value


def hanja_table(files: dict[str, list[str]]) -> dict[str, list[str]]:
    """Kanji → Korean readings for the Joyo and Jinmeiyo kanji that have any."""
    hangul: dict[int, list[str]] = {}
    for cp, field, value in _fields(files["Unihan_Readings.txt"]):
        if field == "kHangul":
            hangul[cp] = list(dict.fromkeys(v.split(":")[0] for v in value.split()))
    variants: dict[int, dict[str, list[int]]] = collections.defaultdict(dict)
    for cp, field, value in _fields(files["Unihan_Variants.txt"]):
        if field in VARIANT_FIELDS:
            variants[cp][field] = [int(v.split("<")[0][2:], 16) for v in value.split()]
    japanese: set[int] = set()
    for cp, field, value in _fields(files["Unihan_OtherMappings.txt"]):
        if field in ("kJoyoKanji", "kJinmeiyoKanji"):
            japanese.add(cp)
            # A value such as U+9830 names the character's other official form.
            for v in value.split():
                if v.startswith("U+"):
                    variants[cp].setdefault("official", []).append(int(v[2:], 16))

    def readings_of(cp: int) -> list[str] | None:
        if cp in hangul:
            return hangul[cp]
        for field in LOOKUP_FIELDS:
            for v in variants[cp].get(field, []):
                if v in hangul:
                    return hangul[v]
        nfc = unicodedata.normalize("NFC", chr(cp))
        return hangul.get(ord(nfc)) if len(nfc) == 1 and ord(nfc) != cp else None

    table: dict[str, list[str]] = {}
    for cp in sorted(japanese):
        found = readings_of(cp)
        if found:
            table[chr(cp)] = found
    return table


def hanja_dart(table: dict[str, list[str]]) -> str:
    entries = [f"{k}{','.join(v)}" for k, v in sorted(table.items())]
    lines = [
        "    '" + " ".join(entries[i:i + ENTRIES_PER_LINE]) + " '"
        for i in range(0, len(entries), ENTRIES_PER_LINE)
    ]
    return (
        "// Generated by tools/extract/build_extract_data.py. Do not edit.\n"
        f"// Source: Unihan {UNIHAN_VERSION} (Unicode License v3), see packages/core/third_party/unihan/.\n"
        "\n"
        f"/// Korean readings of {len(table)} Joyo and Jinmeiyo kanji: space-separated\n"
        "/// entries, each the kanji followed by its readings joined with commas.\n"
        "const String hanjaReadingData =\n" + "\n".join(lines) + ";\n"
    )


def unihan_zip(path: str | None) -> bytes:
    cached = CACHE / f"Unihan-{UNIHAN_VERSION}.zip"
    downloaded = False
    if path:
        data = Path(path).read_bytes()
    elif cached.is_file():
        data = cached.read_bytes()
    else:
        with urllib.request.urlopen(UNIHAN_URL, timeout=120) as r:  # noqa: S310 (fixed https URL)
            data = r.read()
        downloaded = True
    digest = hashlib.sha256(data).hexdigest()
    if digest != UNIHAN_SHA256:
        where = path or (UNIHAN_URL if downloaded else cached)
        raise SystemExit(
            f"{where}: sha256 {digest}, expected {UNIHAN_SHA256} (Unihan {UNIHAN_VERSION})"
            + ("" if path or downloaded else f"; delete {cached} to download again")
        )
    if downloaded:  # keep only a verified copy
        CACHE.mkdir(parents=True, exist_ok=True)
        cached.write_bytes(data)
    return data


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--unihan", help="path to Unihan.zip (default: cache or download)")
    ap.add_argument("--check", action="store_true", help="only compare with the files in the repository")
    args = ap.parse_args(argv)

    wanted = {
        OUT_DIR / "deconjugation_rules.dart": rules_dart(RULES_SOURCE.read_text(encoding="utf-8")),
        OUT_DIR / "hanja_readings.dart": hanja_dart(hanja_table(read_unihan(unihan_zip(args.unihan)))),
    }
    stale = []
    for path, text in wanted.items():
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(str(path.relative_to(REPO)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if args.check:
        for s in stale:
            print(f"out of date: {s} (run python3 tools/extract/build_extract_data.py)", file=sys.stderr)
        return 1 if stale else 0
    print("wrote " + ", ".join(str(p.relative_to(REPO)) for p in wanted))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
